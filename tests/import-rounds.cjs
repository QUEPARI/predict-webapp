const assert=require('node:assert/strict'),path=require('node:path'),{pathToFileURL}=require('node:url');
(async()=>{
  const {resolveImportRound,importStartLabel}=await import(pathToFileURL(path.join(__dirname,'../admin-imports.js')));
  const names=['Eerste ronde','Tweede ronde','Achtste finales','Kwartfinales','Halve finales','Finale'];
  const rounds=names.map((round_name,i)=>({round_name,round_id:'round-'+i}));
  const p={competition:'Dutch Darts Championship',round:'last_48'};
  assert.equal(resolveImportRound(p,rounds).round_id,'round-0');
  assert.equal(resolveImportRound({...p,round:'last_32'},rounds).round_id,'round-1');
  assert.equal(resolveImportRound({...p,competition:'World Championship'},rounds),null);
  assert.equal(resolveImportRound(p,rounds.slice(1)),null);
  assert.equal(resolveImportRound(p,[...rounds,rounds[0]]),null);
  assert.equal(resolveImportRound({...p,round:'last_64'},rounds),null);
  assert.equal(resolveImportRound({...p,round:null},rounds),null);
  assert.equal(resolveImportRound({...p,round:'quarter_finals'},rounds).round_id,'round-3');
  assert.equal(resolveImportRound({...p,round:'final'},[...rounds,rounds[5]]),null);
  assert.equal(resolveImportRound({...p,round:' Eerste ronde '},rounds).round_id,'round-0');
  assert.match(importStartLabel('2026-10-16T20:00:00Z'),/22:00/);
  assert.match(importStartLabel('2026-12-16T20:00:00Z'),/21:00/);
  assert.match(importStartLabel(null),/ontbreekt/);
  assert.match(importStartLabel('invalid'),/Ongeldige/);
  console.log('PASS: scoped round mapping, ambiguous and incomplete draws blocked, Dutch summer/winter time and missing time.');
})().catch(e=>{console.error(e);process.exitCode=1;});
